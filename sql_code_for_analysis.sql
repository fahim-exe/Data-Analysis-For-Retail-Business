-- 15. Generate a list of customers who ordered in October but didn’t order in December.

WITH october_customers AS
(
	SELECT
			DISTINCT customer_id
	FROM "FactOrders"
	WHERE
		order_date::date >= '2025-10-01'
		AND
		order_date::date < '2025-11-01'
)
,

december_customers AS
(
	SELECT
			DISTINCT customer_id
	FROM "FactOrders"
	WHERE
		order_date::date >= '2025-12-01'
		AND
		order_date::date < '2026-01-01'
)

SELECT 	
		oc.customer_id AS customer_id,
		dc.full_name,
		dc.email,
		dc.phone,
		dc.city
FROM october_customers AS oc
LEFT JOIN december_customers AS decc
		ON
		oc.customer_id = decc.customer_id
INNER JOIN "DimCustomers" AS dc
		ON
		oc.customer_id = dc.customer_id
WHERE
	decc."customer_id" IS NULL



