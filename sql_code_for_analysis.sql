-- 18. Is there any relationship between payment method and order status?
WITH method_status_count AS
(	
	SELECT 
			fp.method AS pay_method,
			fo.status AS order_status,
			COUNT(DISTINCT fo.order_id) AS no_of_orders
	FROM "FactOrders" fo
	INNER JOIN "FactPayment" fp
			ON
			fo.order_id = fp.order_id
	GROUP BY 1, 2
	
)


SELECT 	
		pay_method,
		order_status,
		no_of_orders,
		ROUND(
			no_of_orders * 100.0 / SUM(no_of_orders) OVER (PARTITION BY pay_method), 2
		) AS rate_of_status	
FROM method_status_count

ORDER BY 1, 2 , 3 DESC

