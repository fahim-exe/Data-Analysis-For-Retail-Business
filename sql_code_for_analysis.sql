-- 18. Is there any relationship between payment method and order status?
WITH method_status_count AS
(	
	SELECT 
			fp.method AS pay_method,
			fo.status AS order_status,
			COUNT(DISTINCT fo.order_id) AS no_of_orders
	FROM "FactOrders" fo
	INNER JOIN "FactPayment" fp
			ON
			fo.order_id = fp.order_id
	GROUP BY 1, 2
	
)


SELECT 	
		pay_method,
		order_status,
		no_of_orders,
		ROUND(
			no_of_orders * 100.0 / SUM(no_of_orders) OVER (PARTITION BY pay_method), 2
		)		
FROM method_status_count

ORDER BY 1, 2 , 3 DESC

-- 19.Do certain cities prefer specific payment methods?

WITH method_city_table AS 
(
	SELECT
			dc.city,
			fp.method AS pay_method,
			COUNT(DISTINCT fo.order_id) AS count_orders
			
			
	FROM "FactOrders" AS fo
	INNER JOIN "DimCustomers" AS dc
			ON
			fo.customer_id = dc.customer_id
	INNER JOIN "FactPayment" AS fp
			ON
			fo.order_id = fp.order_id
	
	GROUP BY 1, 2
	
)

SELECT	
		city,
		pay_method,
		count_orders,
		ROUND(count_orders *100.0 / SUM(count_orders) OVER (PARTITION BY city), 2) AS city_method_percentage

FROM method_city_table

ORDER BY 1, 4 DESC



