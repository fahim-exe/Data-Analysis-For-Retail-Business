-- 14. How does customer purchasing behavior change over time since account creation?

-- without null created at values

WITH order_summary AS (
    SELECT
        fo.order_id,
        fo.customer_id,
        fo.order_date::date AS order_date,
        SUM(foi.quantity) AS total_units,
        SUM(foi.quantity * dp.unit_price) AS gross_sales_proxy
    FROM "FactOrders" fo
    INNER JOIN "FactOrderItems" foi
        ON fo.order_id = foi.order_id
    INNER JOIN "DimProducts" dp
        ON foi.product_id = dp.product_id
    WHERE fo.status = 'Completed'
    GROUP BY
        fo.order_id,
        fo.customer_id,
        fo.order_date
),

customer_order_tenure AS (
    SELECT
        os.order_id,
        os.customer_id,
        os.total_units,
        os.gross_sales_proxy,
        os.order_date - dc.created_at::date AS days_since_account_creation
    FROM order_summary os
    INNER JOIN "DimCustomers" dc
        ON os.customer_id = dc.customer_id
    WHERE dc.created_at IS NOT NULL
      AND os.order_date >= dc.created_at::date
),

tenure_buckets AS (
    SELECT
        *,
        CASE
            WHEN days_since_account_creation BETWEEN 0 AND 30
                THEN '0-30 days'
            WHEN days_since_account_creation BETWEEN 31 AND 60
                THEN '31-60 days'
            WHEN days_since_account_creation BETWEEN 61 AND 90
                THEN '61-90 days'
            ELSE '91+ days'
        END AS account_age_bucket,

        CASE
            WHEN days_since_account_creation BETWEEN 0 AND 30 THEN 1
            WHEN days_since_account_creation BETWEEN 31 AND 60 THEN 2
            WHEN days_since_account_creation BETWEEN 61 AND 90 THEN 3
            ELSE 4
        END AS bucket_order
    FROM customer_order_tenure
)

SELECT
    account_age_bucket,
    COUNT(DISTINCT customer_id) AS active_customers,
    COUNT(DISTINCT order_id) AS completed_orders,
    ROUND(
        COUNT(DISTINCT order_id)::numeric
        / COUNT(DISTINCT customer_id),
        2
    ) AS orders_per_active_customer,
    ROUND(AVG(total_units), 2) AS avg_units_per_order,
    ROUND(AVG(gross_sales_proxy), 2) AS avg_order_value_proxy,
    ROUND(SUM(gross_sales_proxy), 2) AS gross_sales_proxy
FROM tenure_buckets
GROUP BY
    account_age_bucket,
    bucket_order
ORDER BY
    bucket_order;

